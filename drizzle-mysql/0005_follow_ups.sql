CREATE TABLE IF NOT EXISTS `follow_ups` (
  `id` varchar(36) NOT NULL,
  `user_id` varchar(36) NOT NULL,
  `case_id` varchar(36) DEFAULT NULL,
  `booking_id` varchar(36) DEFAULT NULL,
  `domain` varchar(40) DEFAULT NULL,
  `label` varchar(160) NOT NULL,
  `day_offset` int NOT NULL,
  `due_at` datetime(3) NOT NULL,
  `sent_at` datetime(3) DEFAULT NULL,
  `answered_at` datetime(3) DEFAULT NULL,
  `answered_via` varchar(20) DEFAULT NULL,
  `helped` varchar(10) DEFAULT NULL,
  `side_effects` varchar(1000) DEFAULT NULL,
  `comment` varchar(1000) DEFAULT NULL,
  `needs_attention` tinyint(1) NOT NULL DEFAULT 0,
  `reviewer_id` varchar(36) DEFAULT NULL,
  `business_id` varchar(36) DEFAULT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `follow_ups_case_day_uq` (`case_id`, `day_offset`),
  UNIQUE KEY `follow_ups_booking_day_uq` (`booking_id`, `day_offset`),
  KEY `follow_ups_due_idx` (`sent_at`, `due_at`),
  KEY `follow_ups_user_idx` (`user_id`, `sent_at`),
  KEY `follow_ups_reviewer_idx` (`reviewer_id`),
  KEY `follow_ups_business_idx` (`business_id`),
  CONSTRAINT `follow_ups_user_fk` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE,
  CONSTRAINT `follow_ups_case_fk` FOREIGN KEY (`case_id`) REFERENCES `workflow_cases` (`id`) ON DELETE CASCADE,
  CONSTRAINT `follow_ups_booking_fk` FOREIGN KEY (`booking_id`) REFERENCES `bookings` (`id`) ON DELETE CASCADE,
  CONSTRAINT `follow_ups_reviewer_fk` FOREIGN KEY (`reviewer_id`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `follow_ups_business_fk` FOREIGN KEY (`business_id`) REFERENCES `businesses` (`id`) ON DELETE SET NULL
);
