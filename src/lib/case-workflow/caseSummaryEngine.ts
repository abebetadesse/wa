/** Thin adapter over `screenText`: detected exactly when the shared screen says "emergency". */
export function detectEmergency(text: string): { detected: boolean; signals: string[] } {
  const result = screenText(text);
  return { detected: result.level === "emergency", signals: result.level === "emergency" ? result.signs.map((sign) => sign.label) : [] };
}

// ─── Core engine function ─────────────────────────────────────────────────────

/**
 * Parses a free-expression narrative into a CaseSummaryCard.
 *
 * @param narrative - The raw text (or voice-transcribed text) the user submitted.
 * @param preferredLanguage - "en" or "am". When "am" the rawNarrative is also
 *   stored as aiTranslation (a live translation call would be wired in production).
 * @returns A fully populated CaseSummaryCard — never throws.
 */
export function parseCaseNarrative(
  narrative: string,
  preferredLanguage: "en" | "am" = "en"
): CaseSummaryCard {
  const lower = narrative.toLowerCase().trim();

  // ─── 1. Urgency classification ───────────────────────────────────────────
  let crisisMessage: string | undefined;
  const screen = screenText(narrative);
  const urgencyFlag = FLAG_FOR_LEVEL[screen.level];
  const emergency = { detected: screen.level === "emergency", signals: screen.level === "emergency" ? screen.signs.map((sign) => sign.label) : [] };

  if (urgencyFlag === "emergency") {
    crisisMessage =
      "Your message indicates you or someone you know may be in immediate danger. " +
      `${EMERGENCY_GUIDANCE} You can also reach out to a trusted person right now. ` +
      "The platform's counsellors are NOT a substitute for emergency services.";
  }

  // ─── 2. Domain classification ─────────────────────────────────────────────
  const domainScores = Object.entries(DOMAIN_SIGNALS).map(([domain, signals]) => {
    const score = signals.reduce(
      (acc, signal) => acc + (lower.includes(signal.toLowerCase()) ? 1 : 0),
      0
    );
    return { domain: domain as CaseDomain, score };
  });
  domainScores.sort((a, b) => b.score - a.score);
  const primaryDomain: CaseDomain =
    domainScores[0].score > 0 ? domainScores[0].domain : "wellbeing";

  // ─── 3. Sub-domain ───────────────────────────────────────────────────────
  let subDomain = "general";
  for (const [keyword, sub] of Object.entries(SUB_DOMAIN_MAP)) {
    if (lower.includes(keyword.replace(/_/g, " "))) {
      subDomain = sub;
      break;
    }
  }

  // ─── 4. Key symptoms / concerns ──────────────────────────────────────────
  const allSignals = Object.values(DOMAIN_SIGNALS).flat();
  const keySymptoms = [...new Set(
    allSignals.filter((s) => lower.includes(s.toLowerCase()) && s.length > 3)
  )].slice(0, 8);

  // ─── 5. Suggested strands ─────────────────────────────────────────────────
  const suggestedStrands: KnowledgeStrandType[] = [
    ...DOMAIN_DEFAULT_STRANDS[primaryDomain],
  ];
  // Addiction strand if substance keywords present
  if (
    lower.includes("alcohol") ||
    lower.includes("khat") ||
    lower.includes("areke") ||
    lower.includes("addiction") ||
    lower.includes("drug")
  ) {
    suggestedStrands.push("addiction");
  }

  // ─── 6. Headline generation ───────────────────────────────────────────────
  const domainLabel: Record<CaseDomain, string> = {
    wellbeing: "Health & Wellbeing",
    relationships: "Relationships & Family",
    career: "Career & Work",
    legal: "Legal Matter",
    social: "Social & Community",
    spiritual: "Spiritual & Cultural",
  };

  const wordCount = narrative.trim().split(/\s+/).length;
  const headline =
    wordCount <= 12
      ? narrative.trim()
      : `${domainLabel[primaryDomain]} — ${subDomain.replace(/_/g, " ")}`;

  // ─── 7. User intention ───────────────────────────────────────────────────
  const userIntention =
    urgencyFlag === "emergency"
      ? "Crisis support requested"
      : `Seeking guidance and insight on ${domainLabel[primaryDomain].toLowerCase()}`;

  // ─── 8. Confidence score ─────────────────────────────────────────────────
  const matchedSignals = domainScores[0].score;
  const aiConfidence = Math.min(
    95,
    Math.max(30, 40 + matchedSignals * 10 - (preferredLanguage === "am" ? 5 : 0))
  );
  const uniqueStrands = [...new Set(suggestedStrands)];

  return {
    rawNarrative: narrative,
    ...(preferredLanguage === "am" ? { aiTranslation: narrative } : {}),
    headline,
    domain: primaryDomain,
    subDomain,
    userIntention,
    keySymptoms,
    urgencyFlag,
    emergencyDetected: emergency.detected,
    emergencySignals: emergency.signals,
    suggestedStrandDetails: uniqueStrands.map((strand) => ({
      strand,
      ...STRAND_TIER_DETAILS[strand],
    })),
    ...(crisisMessage ? { crisisMessage } : {}),
    suggestedStrands: uniqueStrands as KnowledgeStrandType[],
    aiConfidence,
  };
}

/**
 * Validates that a CaseSummaryCard passes the mandatory safety gate
 * before being allowed to proceed to a paid expert session.
 *
 * Emergency cards are NOT blocked — they are routed differently (crisis flow).
 * Returns { allowed: true } or { allowed: false, reason: string }.
 */
export function validateSummaryCardForSession(card: CaseSummaryCard): {
  allowed: boolean;
  reason?: string;
} {
  if (card.emergencyDetected || card.urgencyFlag === "emergency") {
    return { allowed: false, reason: "Emergency signals must use the emergency support route instead of a standard case session." };
  }
  if (!card.headline || card.headline.trim().length < 3) {
    return { allowed: false, reason: "Headline is too short to start a session." };
  }
  if (card.aiConfidence < 25) {
    return {
      allowed: false,
      reason:
        "Confidence is too low to proceed. Please provide more detail about your concern.",
    };
  }
  if (!card.endorsedByUser) {
    return {
      allowed: false,
      reason: "You must confirm the summary card before the session can begin.",
    };
  }
  return { allowed: true };
}

