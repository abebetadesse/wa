/**
 * caseSummaryEngine.ts
 *
 * Enhancement 3 – AI Case Summary Engine
 *
 * Parses a user's free-expression narrative (text or transcribed voice) into a
 * structured CaseSummaryCard. The card is presented to the user for endorsement
 * before a formal case session starts.
 *
 * Safety contract:
 *  - The engine NEVER diagnoses, prescribes, or replaces emergency services.
 *  - "emergency" urgencyFlag cards are returned to the caller so they can
 *    short-circuit to a crisis flow immediately without human expert review.
 *  - All text generation is purely parsing / classification — no LLM is called
 *    here; the heavy AI is deferred to the evaluation pipeline.
 *
 * Domain firewall:
 *  - Domain A (scientific) keywords drive urgencyFlag and keySymptoms.
 *  - Domain B (cultural) keywords affect suggestedStrands only and never
 *    influence urgency or symptom classification.
 */

import type { KnowledgeStrandType } from "@/lib/knowledge/types";
import { EMERGENCY_GUIDANCE } from "@/lib/safety/emergencyContacts";
import { screenText, type UrgencyLevel } from "@/server/safety/urgency";

// ─── Types ────────────────────────────────────────────────────────────────────

export type UrgencyFlag = "none" | "watch" | "urgent" | "emergency";
export type StrandTier = "biomedical" | "evidence-informed" | "traditional" | "cultural";

export interface SuggestedStrandDetail {
  strand: KnowledgeStrandType;
  tier: StrandTier;
  rationale: string;
}

export type CaseDomain =
  | "wellbeing"
  | "relationships"
  | "career"
  | "legal"
  | "social"
  | "spiritual";

export interface CaseSummaryCard {
  /** Unique ID for the card — generated by the caller when persisting to DB */
  id?: string;
  endorsedByUser?: boolean;
  /** Original narrative text submitted by the user */
  rawNarrative: string;
  /** English translation of the narrative when input was in Amharic */
  aiTranslation?: string;
  /** One-line summary of the concern */
  headline: string;
  /** Primary domain selected by the engine */
  domain: CaseDomain;
  /** Finer-grained sub-category (e.g. "marital_conflict", "job_search") */
  subDomain: string;
  /** Short description of what the user is seeking */
  userIntention: string;
  /** Key symptom or concern phrases extracted from the narrative */
  keySymptoms: string[];
  /** Emergency / urgency flag */
  urgencyFlag: UrgencyFlag;
  emergencyDetected: boolean;
  emergencySignals: string[];
  suggestedStrandDetails: SuggestedStrandDetail[];
  /** Crisis resource message — only populated when urgencyFlag === "emergency" */
  crisisMessage?: string;
  /** Strands recommended for the case evaluation pipeline */
  suggestedStrands: KnowledgeStrandType[];
  /** Engine confidence score 0–100 */
  aiConfidence: number;
}

