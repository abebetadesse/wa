/**
 * Maps a TraditionalMedicineItem cleanly into the legacy MedicinalPlant structure
 * so all existing components and engines work with full backwards compatibility.
 */
export function toMedicinalPlant(item: TraditionalMedicineItem): MedicinalPlant {
  return {
    id: item.id,
    scientificName: item.scientificName,
    vernacularName: item.vernacularName,
    amharicName: item.amharicName,
    growthForm: item.growthForm,
    habitat: item.habitat,
    location: item.location,
    geographicalDistribution: item.location,
    plantParts: item.plantParts,
    traditionalUse: item.traditionalUse,
    action: item.pharmacologicalActions.join("; "),
    modeOfAction: item.pharmacologicalActions.slice(0, 3).join(", "),
    modeOfPreparation: `${item.traditionalPreparation.methodAmharic} — ${item.traditionalPreparation.instructionsAmharic} (${item.traditionalPreparation.instructionsEnglish})`,
    dosage: item.traditionalPreparation.dosageTradition,
    biochemicalComposition: item.biochemicalComposition,
    activeIngredients: item.activeIngredients,
    safetyNotes: `${item.safetyNotes} [Classification: ${item.safetyClassification}]`,
    diseasesTreated: item.diseasesTreated,
    source: `${item.source} ${item.manuscriptReference ? `• ${item.manuscriptReference.bookTitle} ${item.manuscriptReference.chapterOrSection}` : ""}`,
    sourceUrl: "https://ephi.gov.et/research/traditional-modern-medicine/",
    pubmedEvidence: item.pubmedEvidence,
  };
}

/**
 * Filter intensive traditional medicines with full text, category, safety, and manuscript support.
 */
export function filterTraditionalMedicines(options: {
  query?: string;
  category?: string;
  safety?: string;
  manuscriptOnly?: boolean;
}): TraditionalMedicineItem[] {
  const { query, category, safety, manuscriptOnly } = options;
  const q = (query ?? "").trim().toLowerCase();

  return INTENSIVE_TRADITIONAL_MEDICINES.filter((item) => {
    // Manuscript filter
    if (manuscriptOnly && !item.manuscriptReference) return false;

    // Safety filter
    if (safety && safety !== "all" && item.safetyClassification !== safety) return false;

    // Category filter
    if (category && category !== "all") {
      const matchesCat =
        item.primaryCategory === category ||
        (item.secondaryCategories ?? []).includes(category as TraditionalTherapeuticCategory);
      if (!matchesCat) return false;
    }

    // Query filter
    if (!q) return true;

    const searchBlob = [
      item.amharicName,
      item.geezName ?? "",
      item.vernacularName,
      item.englishName,
      item.scientificName,
      item.botanicalFamily,
      item.growthForm,
      item.habitat,
      item.location,
      item.categoryAmharic,
      item.traditionalUse,
      item.traditionalPreparation.methodAmharic,
      item.traditionalPreparation.instructionsAmharic,
      item.traditionalPreparation.instructionsEnglish,
      item.traditionalPreparation.dosageTradition,
      item.diseasesTreated.join(" "),
      item.activeIngredients.join(" "),
      item.biochemicalComposition.join(" "),
      item.safetyNotes,
      item.contraindications.join(" "),
      item.manuscriptReference?.bookTitle ?? "",
      item.manuscriptReference?.chapterOrSection ?? "",
    ]
      .join(" ")
      .toLowerCase();

    return searchBlob.includes(q);
  });
}
