export function searchRawFoodMaterials(query: string, category?: FoodCategory): RawFoodMaterial[] {
  const normalized = query.trim().toLocaleLowerCase();
  let list = ALL_RAW_FOOD_MATERIALS;
  if (category) list = list.filter((item) => item.category === category);

  if (!normalized) return list;

  return list.filter((item) =>
    [
      item.name,
      item.nameAmharic,
      item.scientificName,
      item.partUsed,
      item.category,
      ...item.useAsIngredient,
    ].some((value) => value.toLocaleLowerCase().includes(normalized)),
  );
}

